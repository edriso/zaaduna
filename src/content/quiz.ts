/**
 * Days since the Unix epoch for the civil date in `tz` — a stable integer
 * that increments by exactly 1 each local calendar day (same discipline as
 * content/poll.ts: read in the bot's timezone, never the host clock).
 */
function dayNumberInTz(now: Date, tz: string): number {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: tz,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(now);
  const get = (t: string): number => Number(parts.find((p) => p.type === t)!.value);
  return Math.floor(Date.UTC(get('year'), get('month') - 1, get('day')) / 86_400_000);
}

/**
 * A stable, epoch-anchored week number in `tz`. The quiz fires every Friday
 * (7 days apart), so this advances by exactly 1 per fire and the whole pool is
 * walked before any repeat — no saved state, restart-safe by construction.
 * Exported for tests.
 */
export function weekNumberInTz(now: Date = new Date(), tz: string = config.timezone): number {
  return Math.floor(dayNumberInTz(now, tz) / 7);
}

/**
 * Build the weekly situational-adab quiz as a Telegram quiz PollSpec: one
 * correct answer + an explanation shown after voting. Anonymous, picked by
 * week number so it rotates weekly. Defaults to now + config.timezone so the
 * scheduler calls it with no args; the args exist for tests.
 */
export function buildWeeklyQuiz(now: Date = new Date(), tz: string = config.timezone): PollSpec {
  const q = adabQuizzes[weekNumberInTz(now, tz) % adabQuizzes.length];
  return {
    question: `${QUESTION_LEAD}\n\n${q.situation}`,
    options: q.options,
    type: 'quiz',
    correctOptionId: q.correctIndex,
    explanation: q.explanation,
    isAnonymous: true,
    // Open ~6 days so the week's readers can answer; closes before next Friday.
    closeAfterHours: 24 * 6,
  };
}
